# Задача 3: Чтение и запись в файл
# Задание: Напиши функцию, которая принимает имя текстового файла и строку.
#  Функция должна записать эту строку в файл. Затем напиши другую функцию,
#  которая считывает содержимое этого файла и выводит его на экран.


def write_to_file(file_name, text):
    # Используем контекстный менеджер 'with', чтобы автоматически закрыть файл после записи
    with open(file_name, 'w') as file:
        file.write(text)  # Записываем текст в файл

def read_from_file(file_name):
    # Используем контекстный менеджер 'with', чтобы автоматически закрыть файл после чтения
    with open(file_name, 'r') as file:
        print(file.read())  # Читаем и выводим содержимое файла

# Получаем имя файла и текст для записи от пользователя
file_name, content = input('Enter file name and text to write: ').split(' ', 1)

# Записываем текст в файл
write_to_file(file_name, content)
# Читаем и выводим содержимое файла
read_from_file(file_name)
